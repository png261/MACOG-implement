"""
Tools available to the Security Prover agent.

file_read             — built-in strands_tools; lets the LLM read .tf files.
file_write            — built-in strands_tools; lets the LLM write Rego files.
generate_rego_suite   — parses I-IR and writes focused Rego files per rule group.
run_encryption_check  — conftest/Python check for encryption rules.
run_network_check     — conftest/Python check for network/ingress rules.
run_access_check      — conftest/Python check for IAM/secret access rules.
run_governance_check  — conftest/Python check for tagging and residency rules.
run_scanner_check     — optional Checkov/Regula scanner cross-check.

LLM call sequence:
  Turn 1: generate_rego_suite (writes policy files)
  Turn 2: run_encryption_check + run_network_check + run_access_check +
          run_governance_check + run_scanner_check (parallel)
"""
