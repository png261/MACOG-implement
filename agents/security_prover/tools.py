# ── Tool: run_governance_check ────────────────────────────────────────────────

@tool(context=True)
def run_governance_check(
    session_dir: str = "",
    constraints_json: str = "{}",
    tool_context: ToolContext = None,
) -> str:
    """
    Run conftest against governance.rego; falls back to Python governance rules.

    Checks: required tags on taggable resources and region/data-residency allow-list.
    Writes state key: governance_violations.
    Returns JSON: {violations, proof_traces, source}.
    """
    constraints: dict[str, Any] = {}
