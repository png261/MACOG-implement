_ENCRYPTION_REGO = """\
package main

# Generated by MACOG Security Prover — encryption rule group
# effects: encrypt_at_rest

deny[msg] {{
    resource := input.resource.aws_s3_bucket[name]
    not resource.server_side_encryption_configuration
    msg := sprintf("aws_s3_bucket.%v: missing server_side_encryption_configuration", [name])
}}

deny[msg] {{
    resource := input.resource.aws_db_instance[name]
    not resource.storage_encrypted == true
    msg := sprintf("aws_db_instance.%v: missing storage_encrypted = true", [name])
}}

deny[msg] {{
    resource := input.resource.aws_ebs_volume[name]
    not resource.encrypted == true
    msg := sprintf("aws_ebs_volume.%v: missing encrypted = true", [name])
}}
"""

_NETWORK_REGO = """\
package main

# Generated by MACOG Security Prover — network rule group
# effects: restricted_ingress

deny[msg] {{
    resource := input.resource.aws_security_group[name]
    ingress := resource.ingress[_]
    cidr := ingress.cidr_blocks[_]
    cidr == "0.0.0.0/0"
    msg := sprintf("aws_security_group.%v: unrestricted ingress 0.0.0.0/0", [name])
}}

deny[msg] {{
    resource := input.resource.aws_db_instance[name]
    resource.publicly_accessible == true
    msg := sprintf("aws_db_instance.%v: publicly_accessible must be false", [name])
}}
"""

_ACCESS_REGO = """\
package main

# Generated by MACOG Security Prover — access rule group
# effects: least_privilege, no_hardcoded_secrets

deny[msg] {{
    resource := input.resource.aws_iam_policy[name]
    doc := json.unmarshal(resource.policy)
    statement := doc.Statement[_]
    statement.Action == "*"
    msg := sprintf("aws_iam_policy.%v: wildcard Action in IAM policy", [name])
}}

deny[msg] {{
    resource := input.resource.aws_iam_policy[name]
    doc := json.unmarshal(resource.policy)
    statement := doc.Statement[_]
    statement.Resource == "*"
    msg := sprintf("aws_iam_policy.%v: wildcard Resource in IAM policy", [name])
}}
"""

_GOVERNANCE_REGO = """\
package main

# Generated by MACOG Security Prover — governance rule group
# effects: tag_required, residency_eu

taggable_types := {
    "aws_instance",
    "aws_vpc",
    "aws_subnet",
    "aws_db_instance",
    "aws_s3_bucket",
    "aws_lb",
    "aws_security_group",
}

deny[msg] {
    resources := input.resource[type]
    taggable_types[type]
    resource := resources[name]
    not resource.tags
    msg := sprintf("%v.%v: missing tags block", [type, name])
}

deny[msg] {
    resources := input.resource[type]
    taggable_types[type]
    resource := resources[name]
    resource.tags
    not resource.tags.Environment
    msg := sprintf("%v.%v: missing Environment tag", [type, name])
}
"""


# ── Tool: generate_rego_suite ─────────────────────────────────────────────────

@tool(context=True)
def generate_rego_suite(
    session_dir: str = "",
    iir_json: str = "",
    tool_context: ToolContext = None,
) -> str:
    """
    Parse I-IR effects and resource list; generate focused Rego policy files in
    {session_dir}/policy/ — one file per rule group (encryption, network, access, governance).

    Detects which rule groups apply from iir_json effects or from HCL resource types.
    Only writes rule groups that are relevant to the detected resources.

    Writes state key: rego_files.
    Returns JSON: {policy_files, effects_detected, logs}.
    """
    if not session_dir or not os.path.isdir(session_dir):
        return json.dumps({"policy_files": [], "effects_detected": [],
                           "logs": "No valid session_dir provided"})

    logs: list[str] = []
    effects: list[str] = []
    resource_types: list[str] = []

    # Parse I-IR for effects and resource types
    if iir_json:
        try:
            iir = json.loads(iir_json)
            nodes = iir.get("nodes", iir.get("resources", []))
            for node in nodes:
                rtype = node.get("resource_type", node.get("kind", node.get("type", "")))
                if rtype:
                    resource_types.append(rtype)
                effs = node.get("effects", node.get("specs", {}).get("effects", []))
                if isinstance(effs, list):
                    effects.extend(effs)
                elif isinstance(effs, str):
                    effects.extend(e.strip() for e in effs.split(",") if e.strip())
            logs.append(f"Parsed I-IR: {len(nodes)} resources, effects={effects}")
        except (json.JSONDecodeError, KeyError, TypeError) as exc:
            logs.append(f"I-IR parse error: {exc}; falling back to HCL scan")

    # Fallback: derive from HCL
    if not resource_types and not effects:
        hcl = _read_tf_dir(session_dir)
        for rtype in ("aws_s3_bucket", "aws_db_instance", "aws_ebs_volume",
                       "aws_security_group", "aws_iam_policy", "aws_instance"):
            if rtype in hcl:
                resource_types.append(rtype)
        if any(r in resource_types for r in ("aws_s3_bucket", "aws_db_instance", "aws_ebs_volume")):
            effects.append("encrypt_at_rest")
        if "aws_security_group" in resource_types or "aws_db_instance" in resource_types:
            effects.append("restricted_ingress")
        if "aws_iam_policy" in resource_types:
            effects.append("least_privilege")
        if any(r.startswith("aws_") for r in resource_types):
            effects.append("tag_required")
        logs.append(f"HCL scan: resource_types={resource_types}, effects={effects}")

    # Determine which rule groups to write
    write_encryption = (
        "encrypt_at_rest" in effects
        or any(r in resource_types for r in ("aws_s3_bucket", "aws_db_instance", "aws_ebs_volume"))
    )
    write_network = (
        "restricted_ingress" in effects or "least_privilege" in effects
        or any(r in resource_types for r in ("aws_security_group", "aws_db_instance"))
    )
    write_access = (
        "least_privilege" in effects or "no_hardcoded_secrets" in effects
        or "aws_iam_policy" in resource_types
        or True  # always check for hardcoded secrets
    )
    write_governance = (
        "tag_required" in effects
        or "residency_eu" in effects
        or any(r.startswith("aws_") for r in resource_types)
    )

    policy_dir = os.path.join(session_dir, "policy")
    os.makedirs(policy_dir, exist_ok=True)

    policy_files: list[dict] = []

    if write_encryption:
        path = os.path.join(policy_dir, "encryption.rego")
        with open(path, "w") as fh:
            fh.write(_ENCRYPTION_REGO)
        policy_files.append({"path": path, "rule_group": "encryption"})
        logs.append("Wrote encryption.rego")

    if write_network:
        path = os.path.join(policy_dir, "network.rego")
        with open(path, "w") as fh:
            fh.write(_NETWORK_REGO)
        policy_files.append({"path": path, "rule_group": "network"})
        logs.append("Wrote network.rego")

    if write_access:
        path = os.path.join(policy_dir, "access.rego")
        with open(path, "w") as fh:
            fh.write(_ACCESS_REGO)
        policy_files.append({"path": path, "rule_group": "access"})
        logs.append("Wrote access.rego")

    if write_governance:
        path = os.path.join(policy_dir, "governance.rego")
        with open(path, "w") as fh:
            fh.write(_GOVERNANCE_REGO)
        policy_files.append({"path": path, "rule_group": "governance"})
        logs.append("Wrote governance.rego")

    if tool_context is not None:
        tool_context.agent.state.set("rego_files", json.dumps(policy_files))

    return json.dumps({
        "policy_files": policy_files,
        "effects_detected": list(set(effects)),
        "logs": "\n".join(logs),
    })


